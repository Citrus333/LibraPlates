function statusEffects.GetDebuffIdBySpellId(spellId)
    return spellToDebuff[tonumber(spellId) or 0];
end

function statusEffects.IsDebuff(statusId)
    local id = tonumber(statusId) or 0;

    if (id <= 0 or id == 255) then
        return false;
    end

    return debuffs[id] == true or knownBuffs[id] ~= true;
end

function statusEffects.IsBuff(statusId)
    local id = tonumber(statusId) or 0;

    return id > 0 and id ~= 255 and knownBuffs[id] == true;
end

